# Тема: Логические операторы: and, or, not

# Мини проект: Калькулятор
# Создайте простой калькулятор, который может выполнять основные арифметические операции:
# сложение, вычитание, умножение и деление.
#
# Требования:
# Программа должна запрашивать у пользователя два числа и операцию (+, -, *, /).
# Программа должна выполнять выбранную операцию и выводить результат, например: "Результат вычисления 2 + 3 равен 5"
# В противном случае вывести сообщение: "Ввод не может быть обработан".


# Функция для выполнения арифметических операций
def calculator():
    try:
        # Запрашиваем у пользователя два числа и операцию
        num1 = float(input("Введите первое число: "))
        num2 = float(input("Введите второе число: "))
        operation = input("Введите операцию (+, -, *, /): ")

        # Выполняем соответствующую операцию в зависимости от введенного символа
        if operation == "+":
            result = num1 + num2
        elif operation == "-":
            result = num1 - num2
        elif operation == "*":
            result = num1 * num2
        elif operation == "/":
            if num2 != 0:
                result = num1 / num2
            else:
                print("Ошибка: деление на ноль.")
                return
        else:
            print("Ввод не может быть обработан: некорректная операция.")
            return

        # Выводим результат
        print(f"Результат вычисления {num1} {operation} {num2} равен {result}")

    except ValueError:
        # Обработка ошибки, если пользователь вводит некорректные данные (не числа)
        print("Ввод не может быть обработан: введены некорректные данные.")


# Вызов функции калькулятора
calculator()